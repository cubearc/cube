const MASKS: [u32; 4] = [0x3fcff3fc, 0xfc3fcff3, 0xf3fc3fcf, 0xcff3fc3f];
const MC: [u32; 4] = [0xacacacac, 0x59595959, 0xb2b2b2b2, 0x65656565];
fn byte(x: u32, i: usize) -> usize {
    ((x >> (8 * i)) & 255) as usize
}
fn brotl(x: u32, n: u32) -> u32 {
    let mask = (255 >> n) * 0x01010101;
    ((x & mask) << n) | ((x & !mask) >> (8 - n))
}
fn row(x: u32) -> u32 {
    (x & 0xcffccffc)
        ^ (x.rotate_left(8) & 0xf33ff33f)
        ^ (x.rotate_left(16) & 0xfccffccf)
        ^ (x.rotate_left(24) & 0x3ff33ff3)
}
fn round(x: &[u32], alternate: bool) -> [u32; 4] {
    std::array::from_fn(|i| {
        (0..4).fold(0, |v, j| {
            let table = (i + j + if alternate { 2 } else { 0 }) % 4;
            v ^ ((u32::from(S[table][byte(x[j], i)]) * 0x01010101) & MASKS[table])
        })
    })
}
fn schedule(key: &[u8]) -> (Zeroizing<[u32; 52]>, Zeroizing<[u32; 52]>) {
    let mut u = Zeroizing::new([0u32; 4]);
    let mut v = Zeroizing::new([0u32; 4]);
    // Each 64-bit key slice contributes, including the first two slices for
    // 192-/256-bit keys. Go switch cases do not have C's fallthrough.
    for (i, pair) in key.as_chunks::<8>().0.iter().enumerate() {
        u[i] = u32::from_le_bytes([pair[0], pair[2], pair[4], pair[6]]);
        v[i] = u32::from_le_bytes([pair[1], pair[3], pair[5], pair[7]]);
    }
    let mut ek = Zeroizing::new([0u32; 8]);
    ek[..4].copy_from_slice(&round(&u[..], false));
    ek[4..].copy_from_slice(&round(&v[..], true));
    let a = ek[..4].iter().fold(0, |a, x| a ^ x);
    let b = ek[4..].iter().fold(0, |a, x| a ^ x);
    for i in 0..4 {
        ek[i] ^= b;
        ek[i + 4] ^= a;
    }
    let mut dk = Zeroizing::new([
        brotl(row(ek[2].rotate_right(16)), 4),
        brotl(row(ek[3].rotate_right(24)), 2),
        row(ek[0].rotate_right(24)),
        brotl(row(ek[1]), 2),
        brotl(row(ek[7]), 6),
        brotl(row(ek[4].rotate_right(24)), 6),
        brotl(row(ek[5]), 4),
        brotl(row(ek[6].rotate_right(16)), 4),
    ]);
    let mut ce = [[0u32; 4]; 13];
    let mut cd = [[0u32; 4]; 13];
    let mut c = 0xa54ff53au32;
    for i in 0..13 {
        let d = row(if i % 2 == 0 { c.rotate_right(16) } else { c });
        for j in 0..4 {
            ce[i][j] = c ^ MC[j];
            cd[12 - i][j] = d.rotate_right((8 * j) as u32) ^ MC[j];
        }
        c = c.wrapping_add(0x3c6ef372);
    }
    let mut e = Zeroizing::new([0u32; 52]);
    let mut d = Zeroizing::new([0u32; 52]);
    for j in 0..4 {
        d[48 + j] = ek[j] ^ ce[0][j];
    }
    for i in 0..13 {
        let part = (i % 2) * 4;
        for j in 0..4 {
            e[4 * i + j] = ek[part + j] ^ ce[i][j];
        }
        let old: Zeroizing<[u32; 4]> = Zeroizing::new(ek[part..part + 4].try_into().unwrap());
        let next = if i % 2 == 0 {
            [
                old[1].rotate_left(24),
                old[2].rotate_left(16),
                brotl(old[3], 6),
                brotl(old[0], 6),
            ]
        } else {
            [
                brotl(old[3], 2),
                brotl(old[0], 2),
                old[1].rotate_left(8),
                old[2].rotate_left(16),
            ]
        };
        ek[part..part + 4].copy_from_slice(&next);
    }
    for i in 0..12 {
        let part = (i % 2) * 4;
        for j in 0..4 {
            d[4 * i + j] = dk[part + j] ^ cd[i][j];
        }
        let old: Zeroizing<[u32; 4]> = Zeroizing::new(dk[part..part + 4].try_into().unwrap());
        let next = if i % 2 == 0 {
            [
                brotl(old[3], 2),
                old[0].rotate_left(16),
                old[1].rotate_left(8),
                brotl(old[2], 2),
            ]
        } else {
            [
                brotl(old[1], 6),
                old[2].rotate_left(16),
                old[3].rotate_left(24),
                brotl(old[0], 6),
            ]
        };
        dk[part..part + 4].copy_from_slice(&next);
    }
    for (j, rotation) in [16, 8, 0, 24].into_iter().enumerate() {
        e[48 + j] = row(e[48 + j].rotate_right(rotation));
    }
    (e, d)
}
pub(super) fn transform(data: &[u8], key: &[u8], inverse: bool) -> Vec<u8> {
    let (e, d) = schedule(key);
    let k = if inverse { &d } else { &e };
    let mut out = data.to_vec();
    for block in out.as_chunks_mut::<16>().0 {
        let mut x: Zeroizing<[u32; 4]> = Zeroizing::new(std::array::from_fn(|i| {
            u32::from_le_bytes(block[4 * i..4 * i + 4].try_into().unwrap()) ^ k[i]
        }));
        for r in 1..12 {
            *x = round(&x[..], r % 2 == 0);
            for j in 0..4 {
                x[j] ^= k[4 * r + j];
            }
        }
        let last: Zeroizing<[u32; 4]> = Zeroizing::new(std::array::from_fn(|i| {
            (0..4).fold(0, |v, j| {
                v | (u32::from(S[(i + j + 2) % 4][byte(x[j], i)]) << (8 * j))
            }) ^ k[48 + i]
        }));
        for (word, bytes) in last.iter().zip(block.as_chunks_mut::<4>().0) {
            bytes.copy_from_slice(&word.to_le_bytes());
        }
    }
    out
}

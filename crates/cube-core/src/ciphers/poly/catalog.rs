struct Spec {
    name: &'static str,
    description: &'static str,
    reversible: bool,
    output_type: &'static str,
    id: &'static str,
    python: &'static str,
    rust: &'static str,
    command: &'static str,
    parameters: fn() -> schemars::Schema,
    inputs: &'static [c::Port],
    outputs: &'static [c::Port],
    fixture: fn() -> Result<c::Fixture, OperationError>,
    input_max: u64,
    output_max: u64,
    sensitive: &'static [&'static str],
    references: &'static [&'static str],
}
const fn row(s: Spec) -> Row {
    classified_row(s, m::Classification::HistoricalCipher)
}
const fn classified_row(s: Spec, classification: m::Classification) -> Row {
    let Spec {
        name,
        description,
        reversible,
        output_type,
        id,
        python,
        rust,
        command,
        parameters,
        inputs,
        outputs,
        fixture,
        input_max,
        output_max,
        sensitive,
        references,
    } = s;
    let descriptor = o::Descriptor {
        id,
        category: "ciphers",
        description,
        input_type: "text",
        output_type,
        parameters: if sensitive.is_empty() {
            PARAMS
        } else {
            SOLITAIRE_PARAMS
        },
        deterministic: true,
        reversible: Some(reversible),
        command,
        example: "cube cipher --help",
    };
    Row {
        contract: c::Entry {
            operation_version: 1,
            descriptor,
            inputs,
            parameters,
            outputs,
            limits: c::Limits {
                max_input_bytes: Some(input_max),
                max_output_bytes: Some(output_max),
                max_items: None,
                max_work: None,
                max_memory_bytes: None,
            },
            fixture,
        },
        profile: m::Entry {
            descriptor,
            metadata: Some(m::Metadata {
                schema_version: 1,
                canonical_name: name,
                family: "polyalphabetic_polygraphic",
                aliases: &[],
                security: m::Security {
                    classification,
                    limitations: "Historical/challenge use only; no modern confidentiality or authentication. Fillers and aliases can make original spelling unrecoverable.",
                    private_input: !sensitive.is_empty(),
                    private_output: !sensitive.is_empty(),
                    sensitive_parameters: sensitive,
                },
                profile: m::Profile {
                    variant: description,
                    alphabet: "ASCII case-preserving schedules, strict canonical square/tableau profiles, or explicit exact Hill/Digrafid scalars as documented.",
                    key: "Caller-owned typed parameters. Keys <=64 KiB except Running Key <=1 MiB; every parameter transport <=2 MiB.",
                    key_advancement: "Per transformed letter or digraph/group according to the selected named profile; reset at each call.",
                    block_bits: None,
                    output_bits: None,
                },
                resources: &[],
                resource_notes: "Core limits are checked for every direct caller. See operation limits and parameter schema. Playfair text <=2 MiB, serialized report <=16 MiB; Hill <=65536 symbols; Digrafid <=65536 input symbols; Tri-square <=65536 plaintext/98304 ciphertext bytes. Canonical parameters transport <=2 MiB; Hill definition <=64 KiB. Direct-only: no new pipeline adapter or capability grant.",
                rust_api: rust,
                python_api: python,
                references,
            }),
        },
    }
}

fn g(word: u32) -> u32 {
    let [a, b, c, d] = word.to_le_bytes();
    SS0[a as usize]
        ^ SS1[b as usize]
        ^ SS0[c as usize].rotate_left(16)
        ^ SS1[d as usize].rotate_left(16)
}
fn schedule(key: &[u8]) -> Zeroizing<[[u32; 2]; 16]> {
    assert_eq!(key.len(), 16);
    let mut state: Zeroizing<[u32; 4]> = Zeroizing::new(std::array::from_fn(|i| {
        u32::from_be_bytes(key[4 * i..4 * i + 4].try_into().unwrap())
    }));
    let mut keys = Zeroizing::new([[0u32; 2]; 16]);
    for (i, row) in keys.iter_mut().enumerate() {
        let [a, b, c, d] = *state;
        let constant = 0x9e3779b9u32.rotate_left(i as u32);
        *row = [
            g(a.wrapping_add(c).wrapping_sub(constant)),
            g(b.wrapping_sub(d).wrapping_add(constant)),
        ];
        if i % 2 == 0 {
            state[0] = (a >> 8) | (b << 24);
            state[1] = (b >> 8) | (a << 24);
        } else {
            state[2] = (c << 8) | (d >> 24);
            state[3] = (d << 8) | (c >> 24);
        }
    }
    keys
}
fn round(right: [u32; 2], key: [u32; 2]) -> [u32; 2] {
    let mut a = right[0] ^ key[0];
    let mut b = right[1] ^ key[1];
    b = g(b ^ a);
    a = g(a.wrapping_add(b));
    b = g(b.wrapping_add(a));
    [a.wrapping_add(b), b]
}
